function createProduct(
  sku: string,
  name: string,
  category: ProductCosting["category"],
  fabricQty: number,
  fabricRate: number,
  trimsCost: number,
  cuttingCost: number,
  stitchingCost: number,
  finishingCost: number,
  packagingCost: number,
  otherCost: number,
  mrp: number,
  discountPct: number,
  gstPct: number,
  marketplaceCommissionPct: number,
  logisticsCost: number,
  marketingCost: number,
  pricingMultiplier: number,
  expectedReturnsPct: number
): ProductCosting {
  const eco = calculateGarmentEconomics({
    fabricQty,
    fabricRate,
    trimsCost,
    cuttingCost,
    stitchingCost,
    finishingCost,
    packagingCost,
    otherCost,
    mrp,
    discountPct,
    gstPct,
    marketplaceCommissionPct,
    logisticsCost,
    reverseLogisticsCost: 35,
    marketingCost,
    pricingMultiplier,
    expectedReturnsPct,
    targetCogsPct: 20,
  });

  return {
    sku,
    name,
    category,
    marketplaces: ["Myntra", "Amazon", "Flipkart"],
    fabricQty,
    fabricRate,
    trimsCost,
    cuttingCost,
    stitchingCost,
    finishingCost,
    packagingCost,
    otherCost,
    totalCogs: eco.totalCogs,
    mrp,
    discountPct,
    gstPct,
    marketplaceCommissionPct,
    logisticsCost,
    reverseLogisticsCost: 35,
    marketingCost,
    pricingMultiplier,
    targetCogsPct: 20,
    expectedReturnsPct,
    recommendedMrp: eco.recommendedMrp,
    cogsPct: eco.cogsPct,
    cm1: eco.cm1,
    cm2: eco.cm2,
    cm3: eco.cm3,
    status: "Active",
  };
}

